# Arithmetic operations
a = 20
b = 5

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)

# Comparison
print(a > b)
print(a < b)
print(a == b)

# Useful DevSecOps example
total_servers = 10
failed_servers = 2

success_rate = ((total_servers - failed_servers) / total_servers) * 100

print(f"Success rate: {success_rate}%")